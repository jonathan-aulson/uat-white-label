test('author, run and triage a campaign on desktop and mobile', async ({ browser, baseURL }) => {
 const contexts = [];
 const errors = [];
 async function pageFor(email, viewport = { width: 1280, height: 900 }) {
  const context = await browser.newContext({ baseURL, viewport, extraHTTPHeaders: { 'x-dev-user': email } });
  contexts.push(context);
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  return page;
 }
 try {
  const suffix = Date.now().toString(36);
  const email = `browser-${suffix}@example.com`;
  const admin = await pageFor('admin@example.com');
  admin.on('dialog', d => d.accept());
  const call = async (path, method, data) => {
   const response = await admin.request.fetch(path, { method, data });
   expect(response.ok(), await response.text()).toBe(true);
   return response.json();
  };
  await admin.goto('/admin#content');
  await admin.getByLabel('Label', { exact: true }).fill(`Browser release ${suffix}`);
  await admin.getByRole('button', { name: 'Create draft' }).click();
  await expect(admin.getByRole('button', { name: 'Publish…' })).toBeVisible();
  const release = admin.url().split('#content/')[1];
  const releaseData = await call(`/api/admin/releases/${release}`, 'GET');
  releaseData.content.scenarios[0].steps.push({
   id: 'S1-2', text: 'Submit the synthetic form.', expect: 'A confirmation appears.', roles: ['tester']
  });

  await admin.getByRole('textbox', { name: 'Release content JSON' }).fill(JSON.stringify(releaseData.content, null, 2));
  await admin.getByRole('button', { name: 'Publish…' }).click();
  await expect(admin.getByRole('button', { name: 'Make an editable copy' })).toBeVisible();
  await admin.goto('/admin#roster');
  await admin.getByLabel('Email', { exact: true }).fill(email);
  await admin.getByLabel('Name', { exact: true }).fill(`Browser Tester ${suffix}`);
  await admin.getByRole('button', { name: 'Add or reactivate' }).click();
  await expect(admin.getByRole('cell', { name: email, exact: true })).toBeVisible();

  await admin.goto('/admin#campaigns');
  await admin.getByLabel('Name', { exact: true }).fill(`Browser campaign ${suffix}`);
  await admin.getByRole('combobox', { name: 'Release' }).selectOption(release);
  await admin.getByRole('button', { name: 'Create campaign' }).click();
  await expect(admin.getByRole('button', { name: 'Save invitations' })).toBeVisible();
  await admin.locator('.row').filter({ has: admin.locator('span', { hasText: email }) }).getByRole('checkbox').check();
  const invitationsSaved = admin.waitForResponse(r => r.url().endsWith('/invites') && r.request().method() === 'PUT' && r.status() === 200);
  await admin.getByRole('button', { name: 'Save invitations' }).click();
  await invitationsSaved;

  const tester = await pageFor(email);
  await tester.goto('/');
  await tester.getByRole('button', { name: 'Start', exact: true }).click();
  const first = tester.locator('[data-step="S1-1"]');
  await first.getByRole('button', { name: /Passed/ }).click();
  await expect(tester.locator('#saveState')).toHaveText('All changes saved');
  const issue = tester.locator('[data-step="S1-2"]');
  await issue.getByRole('button', { name: /Issue/ }).click();
  const saved = tester.waitForResponse(r => r.url().endsWith('/results/S1-2') && r.request().method() === 'PUT' && r.status() === 200);
  await issue.getByRole('textbox').fill('Synthetic failure: confirmation is missing.');
  await saved;

  const mobile = await pageFor(email, { width: 390, height: 800 });
  await mobile.goto('/');
  await mobile.getByRole('button', { name: 'Resume', exact: true }).click();
  await expect(mobile.locator('[data-step="S1-2"]').getByRole('textbox')).toHaveValue('Synthetic failure: confirmation is missing.');
  expect(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);

  // Only external ADO writes are mocked; the repro is generated by the real local API.
  await admin.route('**/ado-preview', async route => {
   const response = await route.fetch();
   expect(response.ok()).toBe(true);
   await route.fulfill({ json: { ...await response.json(), configured: true } });
  });
  let submissions = 0;
  await admin.route('**/create-ado', async route => {
   submissions++;
   const data = route.request().postDataJSON();
   expect(data.repro).toContain('[S1 / S1-1]');
   expect(data.repro).toContain('[S1 / S1-2]');
   expect(data.repro).toContain('Expected Result:\nA confirmation appears.');
   expect(data.repro).toContain('Actual Result:\nSynthetic failure: confirmation is missing.');
   expect(data.confirmNoPhi).toBe(true);
   const id = decodeURIComponent(new URL(route.request().url()).pathname.split('/').at(-2));
   await call(`/api/admin/findings/result/${encodeURIComponent(id)}`, 'PATCH', { triage: 'Accepted', admin_note: 'Mocked browser test export' });
   await route.fulfill({ json: { ado_id: 9001, ado_url: 'https://dev.azure.com/example/Test/_workitems/edit/9001' } });
  });
  await admin.goto('/admin#findings');
  await admin.getByRole('button', { name: 'Create bug…' }).click();
  const dialog = admin.getByRole('dialog');
  await expect(dialog.getByRole('textbox', { name: /Reproduction/ })).toHaveValue(/Steps to Reproduce:[\s\S]*Expected Result:[\s\S]*Actual Result:/);
  await dialog.getByRole('checkbox').check();
  await dialog.getByRole('button', { name: 'Create bug', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect(submissions).toBe(1);
  await expect(admin.getByText('Bug #9001 linked. Use Open bug to view it.', { exact: true })).toBeVisible();
  for (const tab of ['progress', 'branding', 'documents', 'settings', 'audit']) {
   await admin.goto(`/admin#${tab}`);
   await expect(admin.locator('#main h2')).toBeVisible();
  }
  expect(errors).toEqual([]);
 } finally {
  if (test.info().status !== 'timedOut') for (const context of contexts) await context.close();
 }
});

test('low-contrast branding is advisory and linked PDFs upload unchanged', async ({ page }) => {
 const errors = [];
 page.on('pageerror', e => errors.push(e.message));
 page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
 await page.context().setExtraHTTPHeaders({ 'x-dev-user': 'admin@example.com' });
 await page.goto('/admin#branding');
 const palette = { primary: '#f5f5aa', accent: '#eeeeee', background: '#ffffff', font: 'system' };
 for (const [label, value] of [['Primary', palette.primary], ['Accent', palette.accent], ['Background', palette.background]]) {
  await page.getByLabel(label.toLowerCase(), { exact: true }).evaluate((input, color) => {
   input.value = color; input.dispatchEvent(new Event('input', { bubbles: true }));
  }, value);
 }
 await expect(page.getByText(/Primary\/background contrast.*You can still save/)).toBeVisible();
 const save = page.getByRole('button', { name: 'Save colours', exact: true });
 await expect(save).toBeEnabled();
 const saved = page.waitForResponse(r => r.url().endsWith('/api/admin/branding') && r.request().method() === 'PUT');
 await save.click();
 const response = await saved;
 expect(response.status()).toBe(200);
 expect((await response.json()).check.warnings).toHaveLength(2);
 await expect(page.getByText('Brand colours saved. Contrast warnings are advisory; your palette was not changed.', { exact: true })).toBeVisible();
 await expect(page.getByText(/Contrast ratios:/)).toBeVisible();
 await expect(page.getByText(/Accent\/background contrast.*You can still save/)).toBeVisible();
 const stored = await page.request.get('/api/admin/branding');
 expect(await stored.json()).toMatchObject(palette);
 const invalid = await page.request.put('/api/admin/branding', { data: { ...palette, primary: 'not-a-colour' } });
 expect(invalid.status()).toBe(400);

 const bytes = await pdfFixture(document => {
  pdfLink(document, document.context.obj({ S: 'URI', URI: PDFString.of('https://allata.com/') }));
  document.catalog.set(document.context.obj('OpenAction'), document.context.obj({ S: 'GoTo', D: [document.getPage(0).ref, 'Fit'] }));
 });
 await page.goto('/admin#documents');
 const title = `Linked PDF ${Date.now()}`;
 await page.getByLabel('Title', { exact: true }).fill(title);
 await page.getByRole('textbox', { name: 'Audience roles' }).fill('tester');
 await page.getByLabel('PDF file', { exact: true }).setInputFiles({ name: 'linked-synthetic.pdf', mimeType: 'application/pdf', buffer: Buffer.from(bytes) });
 await page.getByRole('checkbox').check();
 const uploading = page.waitForResponse(r => r.url().includes('/api/admin/documents?') && r.request().method() === 'POST');
 await page.getByRole('button', { name: 'Upload', exact: true }).click();
 const uploaded = await uploading;
 expect(uploaded.status()).toBe(201);
 const info = await uploaded.json();
 expect(info.warnings.join(' ')).toContain('External links are preserved');
 await expect(page.getByText('Uploaded unchanged; links are preserved.', { exact: true })).toBeVisible();
 await expect(page.getByRole('cell', { name: title, exact: true })).toBeVisible();
 const download = await page.request.get(`/api/admin/documents/${info.id}/download`);
 expect(download.ok()).toBe(true);
 expect(await download.body()).toEqual(Buffer.from(bytes));
 expect(errors).toEqual([]);
});
